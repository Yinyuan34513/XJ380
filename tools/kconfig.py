#!/usr/bin/env python3
import argparse
import locale
import os
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
KCONFIG_FILE = ROOT / "Kconfig"
CONFIG_FILE = Path(os.environ.get("KCONFIG_CONFIG", ".config"))
if not CONFIG_FILE.is_absolute():
    CONFIG_FILE = ROOT / CONFIG_FILE
DEFCONFIG_FILE = Path(os.environ.get("KCONFIG_DEFCONFIG", "configs/xj380_defconfig"))
if not DEFCONFIG_FILE.is_absolute():
    DEFCONFIG_FILE = ROOT / DEFCONFIG_FILE
GENERATED_DIR = ROOT / "include" / "generated"
AUTOCONF_H = GENERATED_DIR / "autoconf.h"
AUTO_CONF = GENERATED_DIR / "auto.conf"


def die(message):
    print(f"kconfig: {message}", file=sys.stderr)
    sys.exit(1)


def import_kconfiglib():
    try:
        import kconfiglib
    except ImportError:
        die(
            "Python package 'kconfiglib' is required. "
            "Install it with: python3 -m pip install kconfiglib"
        )
    return kconfiglib


def ensure_supported_locale():
    try:
        locale.setlocale(locale.LC_ALL, "")
        return
    except locale.Error:
        pass

    for name in ("C.UTF-8", "C"):
        try:
            locale.setlocale(locale.LC_ALL, name)
        except locale.Error:
            continue

        os.environ["LC_ALL"] = name
        os.environ["LANG"] = name
        return

    die("no supported locale found; generate a UTF-8 locale or set LC_ALL=C.UTF-8")


def load_kconfig(kconfiglib):
    os.chdir(ROOT)
    os.environ.setdefault("srctree", str(ROOT))
    return kconfiglib.Kconfig(str(KCONFIG_FILE), warn=True, warn_to_stderr=True)


def load_existing_or_default(kconf):
    if CONFIG_FILE.exists():
        kconf.load_config(str(CONFIG_FILE))
    else:
        kconf.load_config(str(DEFCONFIG_FILE), replace=True)


def make_escape(value):
    return value.replace("$", "$$")


def write_make_auto_conf(kconf, kconfiglib):
    try:
        config_name = CONFIG_FILE.relative_to(ROOT).as_posix()
    except ValueError:
        config_name = str(CONFIG_FILE)

    lines = [
        "# Generated by tools/kconfig.py; do not edit.\n",
        f"KCONFIG_CONFIG={config_name}\n",
    ]

    for sym in sorted(kconf.unique_defined_syms, key=lambda item: item.name):
        if not sym.name:
            continue

        value = sym.str_value
        if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            if value in ("y", "m"):
                lines.append(f"CONFIG_{sym.name}={value}\n")
            continue

        if value != "":
            lines.append(f"CONFIG_{sym.name}={make_escape(value)}\n")

    AUTO_CONF.write_text("".join(lines), encoding="utf-8")


def write_outputs(kconf, kconfiglib, write_config):
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    kconf.write_autoconf(str(AUTOCONF_H))
    write_make_auto_conf(kconf, kconfiglib)
    if write_config:
        kconf.write_config(str(CONFIG_FILE), save_old=False)


def cmd_defconfig(args):
    kconfiglib = import_kconfiglib()
    kconf = load_kconfig(kconfiglib)
    kconf.load_config(str(args.defconfig), replace=True)
    write_outputs(kconf, kconfiglib, write_config=True)


def cmd_olddefconfig(args):
    kconfiglib = import_kconfiglib()
    kconf = load_kconfig(kconfiglib)
    load_existing_or_default(kconf)
    write_outputs(kconf, kconfiglib, write_config=True)


def cmd_syncconfig(args):
    kconfiglib = import_kconfiglib()
    kconf = load_kconfig(kconfiglib)
    load_existing_or_default(kconf)
    write_outputs(kconf, kconfiglib, write_config=not CONFIG_FILE.exists())


def cmd_savedefconfig(args):
    kconfiglib = import_kconfiglib()
    kconf = load_kconfig(kconfiglib)
    load_existing_or_default(kconf)
    kconf.write_min_config(str(args.output))


def cmd_menuconfig(args):
    ensure_supported_locale()
    kconfiglib = import_kconfiglib()
    kconf = load_kconfig(kconfiglib)
    load_existing_or_default(kconf)

    try:
        import menuconfig
    except ImportError:
        die(
            "Kconfiglib's menuconfig frontend is unavailable. "
            "Install the full package with: python3 -m pip install kconfiglib"
        )

    menuconfig.menuconfig(kconf)
    write_outputs(kconf, kconfiglib, write_config=True)


def main():
    parser = argparse.ArgumentParser(description="XJ380 Kconfig helper")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("defconfig", help="write .config from the default defconfig")
    p.add_argument("--defconfig", type=Path, default=DEFCONFIG_FILE)
    p.set_defaults(func=cmd_defconfig)

    p = sub.add_parser("olddefconfig", help="refresh .config with current Kconfig defaults")
    p.set_defaults(func=cmd_olddefconfig)

    p = sub.add_parser("syncconfig", help="generate include/generated files")
    p.set_defaults(func=cmd_syncconfig)

    p = sub.add_parser("savedefconfig", help="write a minimal defconfig")
    p.add_argument("--output", type=Path, default=DEFCONFIG_FILE)
    p.set_defaults(func=cmd_savedefconfig)

    p = sub.add_parser("menuconfig", help="open the Kconfig menu UI")
    p.set_defaults(func=cmd_menuconfig)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
